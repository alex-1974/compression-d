#!/usr/bin/env python3
"""Print deterministic framed fixtures; independently validated by Python zlib."""
import importlib.util
import pathlib
import struct
import sys
import zlib

sys.dont_write_bytecode = True

spec = importlib.util.spec_from_file_location('raw_fixtures', pathlib.Path(__file__).with_name('generate-inflate-fixtures.py'))
raw_fixtures = importlib.util.module_from_spec(spec)
spec.loader.exec_module(raw_fixtures)


def optional_gzip(plain, flags):
    header = bytes([31, 139, 8, flags, 0, 0, 0, 0, 0, 255])
    if flags & 4:
        header += struct.pack('<H', 4) + b'\x00\xff\x01\x02'
    if flags & 8:
        header += b'test.bin\0'
    if flags & 16:
        header += b'sample\0'
    if flags & 2:
        header += struct.pack('<H', zlib.crc32(header) & 65535)
    encoder = zlib.compressobj(wbits=-15)
    return header + encoder.compress(plain) + encoder.flush() + struct.pack('<II', zlib.crc32(plain), len(plain))


def generate():
    records = []
    for gzip in [False, True]:
        for name, pattern, length, level, strategy in [
            ('empty', 0, 0, 6, zlib.Z_DEFAULT_STRATEGY),
            ('stored', 1, 5, 0, zlib.Z_DEFAULT_STRATEGY),
            ('fixed', 1, 5, 6, zlib.Z_FIXED),
            ('dynamic', 3, 44000, 6, zlib.Z_DEFAULT_STRATEGY),
            ('overlap', 2, 70000, 6, zlib.Z_DEFAULT_STRATEGY),
            ('huffman', 3, 4400, 6, zlib.Z_HUFFMAN_ONLY),
            ('distances', 5, 70000, 9, zlib.Z_DEFAULT_STRATEGY),
        ]:
            plain = raw_fixtures.plaintext(pattern, length)
            encoder = zlib.compressobj(level=level, wbits=31 if gzip else 15, strategy=strategy)
            encoded = encoder.compress(plain) + encoder.flush()
            assert zlib.decompress(encoded, wbits=31 if gzip else 15) == plain
            records.append((('g-' if gzip else 'z-') + name, gzip, pattern, length, encoded))
    for flags in [1, 2, 4, 8, 16, 31]:
        plain = b'hello'
        encoded = optional_gzip(plain, flags)
        assert zlib.decompress(encoded, wbits=31) == plain
        records.append((f'g-flags-{flags}', True, 1, 5, encoded))
    lines = [
        '// Generated by scripts/generate-framing-fixtures.py; zlib ' + zlib.ZLIB_VERSION,
        'module framing_fixtures;',
        'struct FrameFixture { string name; bool gzip; uint pattern; size_t length; string hex; }',
        'immutable FrameFixture[] frameFixtures = [',
    ]
    for name, gzip, pattern, length, data in records:
        lines.append(f'    FrameFixture("{name}", {str(gzip).lower()}, {pattern}, {length},')
        chunks = [data.hex()[i:i + 96] for i in range(0, len(data) * 2, 96)]
        for index, chunk in enumerate(chunks):
            lines.append('        "' + chunk + ('"),' if index == len(chunks) - 1 else '" ~'))
    return '\n'.join(lines + ['];', ''])


if __name__ == '__main__':
    print(generate(), end='')
