#!/usr/bin/env python3
"""Print the deterministic D raw-DEFLATE corpus; zlib is only a test oracle.

Use --check PATH to verify checked-in bytes against this zlib version. Different
zlib encoders may produce different valid bytes: decoder tests use saved fixtures.
"""
import argparse
import pathlib
import zlib


def plaintext(pattern, length):
    data = bytearray()
    seed = 12345
    for index in range(length):
        seed = (seed * 1664525 + 1013904223) & 0xFFFFFFFF
        if pattern == 0:
            value = 0
        elif pattern == 1:
            value = b"hello"[index % 5]
        elif pattern == 2:
            value = ord('A')
        elif pattern == 3:
            value = b"the quick brown fox jumps over the lazy dog\n"[index % 44]
        elif pattern == 4:
            value = (seed >> 24) & 255
        elif pattern == 5:
            value = index % 251
        else:
            raise ValueError(pattern)
        data.append(value)
    return bytes(data)


def generate():
    specs = [
        ('empty-stored', 0, 0, 0, zlib.Z_DEFAULT_STRATEGY),
        ('empty-fixed', 0, 0, 6, zlib.Z_FIXED),
        ('hello-stored', 1, 5, 0, zlib.Z_DEFAULT_STRATEGY),
        ('hello-fixed', 1, 5, 6, zlib.Z_FIXED),
        ('stored-251', 5, 753, 0, zlib.Z_DEFAULT_STRATEGY),
        ('fixed-overlap-wrap', 2, 70000, 6, zlib.Z_FIXED),
        ('dynamic-text', 3, 44000, 6, zlib.Z_DEFAULT_STRATEGY),
        ('dynamic-overlap-wrap', 2, 70000, 6, zlib.Z_DEFAULT_STRATEGY),
        ('dynamic-huffman-only', 3, 4400, 6, zlib.Z_HUFFMAN_ONLY),
        ('dynamic-rle', 2, 70000, 6, zlib.Z_RLE),
        ('random-default', 4, 2048, 6, zlib.Z_DEFAULT_STRATEGY),
        ('fixed-distances', 5, 70000, 9, zlib.Z_FIXED),
        ('dynamic-distances', 5, 70000, 9, zlib.Z_DEFAULT_STRATEGY),
        ('mixed-sync', 3, 8800, 6, zlib.Z_DEFAULT_STRATEGY),
        ('mixed-full', 5, 10040, 6, zlib.Z_DEFAULT_STRATEGY),
    ]
    records = []
    for name, pattern, length, level, strategy in specs:
        plain = plaintext(pattern, length)
        encoder = zlib.compressobj(level=level, wbits=-15, strategy=strategy)
        if name.startswith('mixed-'):
            split = len(plain) // 2
            mode = zlib.Z_SYNC_FLUSH if name == 'mixed-sync' else zlib.Z_FULL_FLUSH
            encoded = encoder.compress(plain[:split]) + encoder.flush(mode)
            encoded += encoder.compress(plain[split:]) + encoder.flush()
        else:
            encoded = encoder.compress(plain) + encoder.flush()
        assert zlib.decompress(encoded, wbits=-15) == plain
        records.append((name, pattern, length, encoded))
    lines = [
        '// Generated by scripts/generate-inflate-fixtures.py; zlib ' + zlib.ZLIB_VERSION,
        '// Encoded bytes were independently decoded by zlib before emission.',
        'module inflate_fixtures;',
        'struct Fixture { string name; uint pattern; size_t length; string hex; }',
        'immutable Fixture[] fixtures = [',
    ]
    for name, pattern, length, encoded in records:
        hexdata = encoded.hex()
        lines.append(f'    Fixture("{name}", {pattern}, {length},')
        chunks = [hexdata[i:i + 96] for i in range(0, len(hexdata), 96)]
        for i, chunk in enumerate(chunks):
            lines.append('        "' + chunk + ('"),' if i == len(chunks) - 1 else '" ~'))
    lines += ['];', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', type=pathlib.Path)
    args = parser.parse_args()
    source = generate()
    if args.check:
        if args.check.read_text() != source:
            raise SystemExit('Fixture source differs (including recorded zlib version).')
        print('Fixtures match zlib ' + zlib.ZLIB_VERSION)
    else:
        print(source, end='')
